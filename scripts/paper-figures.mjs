// Draws the paper's Feynman diagrams with feynjs and writes them as TikZ-Feynman, so the paper
// compiles with pdflatex and every figure is made by the software it describes.
//
//   node scripts/paper-figures.mjs        (after npm run build)
//
// paper/figures/src/<name>.feyn  ->  paper/figures/tikz/<name>.tex
// engines.feyn is drawn once per layout engine  ->  paper/figures/tikz/engine-<engine>.tex
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, basename, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { toTikz } from "../dist/feynjs.mjs";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(repo, "paper/figures/src");
const tikzDir = join(repo, "paper/figures/tikz");

/** Length of one propagator in cm. Panels are drawn full size and scaled together in the paper
 * (\resizebox), so their lines and labels keep the proportions of a full-size figure. */
const UNIT = { figure: 1.4, panel: 1.4 };

/** The engines compared in one figure: each a directive line put in front of engines.feyn. */
const ENGINES = {
  v2: "",
  manual: "layout: manual\npp at (0, 0)\nd1 at (0.7, 1.5)",
  plane: "final plane: on",
  grid: "layout: grid",
  "grid-iso": "layout: grid\ngrid: iso",
};

drawPaperFigures();

function drawPaperFigures() {
  mkdirSync(tikzDir, { recursive: true });
  for (const file of feynSources()) {
    if (basename(file) === "engines.feyn") drawEachEngine(file);
    else writeFigure(basename(file, ".feyn"), readFileSync(file, "utf8"), UNIT.figure);
  }
}

function feynSources() {
  return readdirSync(sourceDir).filter((f) => f.endsWith(".feyn")).sort().map((f) => join(sourceDir, f));
}

function drawEachEngine(file) {
  const source = readFileSync(file, "utf8");
  for (const [engine, directives] of Object.entries(ENGINES)) {
    writeFigure(`engine-${engine}`, withDirectives(directives, source), UNIT.panel);
  }
}

function withDirectives(directives, source) {
  return directives ? `${directives}\n${source}` : source;
}

function writeFigure(name, source, unit) {
  const tikz = toTikz(source, { unit, standalone: false });
  writeFileSync(join(tikzDir, `${name}.tex`), `% Generated by scripts/paper-figures.mjs from feynjs source. Do not edit.\n${tikz}\n`);
  console.log(`paper/figures/tikz/${name}.tex`);
}
