// The paper's tables, made from the measurements in paper/results (never typed by hand):
//   paper/results/platforms-{before,after}/*.json   scripts/platform-hashes*.mjs, each runtime
//   paper/results/speed/*.json                      scripts/paper-bench.mjs, each runtime
//   paper/results/speed/tex.json                    scripts/paper-tex-bench.mjs
// -> paper/tables/platforms.tex, paper/tables/speed.tex
//
//   node scripts/paper-tables.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const RESULTS = "paper/results", TABLES = "paper/tables";
const REFERENCE = "node-arm64.json";
const ORDER = ["node", "deno", "bun", "chromium", "firefox", "webkit", "quickjs"];

writeFileSync(join(TABLES, "platforms.tex"), platformsTable());
writeFileSync(join(TABLES, "speed.tex"), speedTable());
console.log("paper/tables/platforms.tex, paper/tables/speed.tex");

// ---------------------------------------------------------------------------------------------
// Platforms: how many diagrams each runtime draws differently from the reference, before and
// after the portable maths.

function platformsTable() {
  const before = runsIn("platforms-before"), after = runsIn("platforms-after");
  const names = [...new Set([...Object.keys(before), ...Object.keys(after)])].sort(byRuntimeOrder);
  const count = Object.values(after)[0]?.count ?? 0;
  const rows = names.map((name) => {
    const run = after[name] ?? before[name];
    return [runtimeName(run), jsEngine(run.engine), platformName(run.platform, name),
      differing(before, name), differing(after, name)].join(" & ") + " \\\\";
  });
  return [
    `% Generated by scripts/paper-tables.mjs from ${RESULTS}/platforms-*. Do not edit.`,
    "\\begin{tabular}{l l l r r}",
    "\\toprule",
    `Runtime & JavaScript engine & Platform & \\multicolumn{2}{c}{Diagrams drawn differently (of ${count})} \\\\`,
    " & & & before & after \\\\",
    "\\midrule",
    ...rows,
    "\\bottomrule",
    "\\end{tabular}",
    "",
  ].join("\n");
}

function runsIn(folder) {
  const dir = join(RESULTS, folder);
  if (!existsSync(dir)) return {};
  return Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => [f, JSON.parse(readFileSync(join(dir, f), "utf8"))]));
}

/** Diagrams this run draws differently from the reference run of the same code; "ref" for it. */
function differing(runs, name) {
  const run = runs[name], reference = runs[REFERENCE];
  if (!run || !reference) return "---";
  if (name === REFERENCE) return "ref.";
  return String(Object.keys(reference.hashes).filter((k) => reference.hashes[k] !== run.hashes[k]).length);
}

function byRuntimeOrder(a, b) {
  const rank = (n) => (n === REFERENCE ? -1 : ORDER.findIndex((o) => n.startsWith(o)));
  return rank(a) - rank(b) || a.localeCompare(b);
}

function runtimeName(run) {
  const [name, version] = run.engine.split(" ");
  const pretty = { node: "Node.js", deno: "Deno", bun: "Bun", chromium: "Chromium", firefox: "Firefox", webkit: "WebKit (Safari)", "quickjs-wasm": "QuickJS in WebAssembly" }[name.toLowerCase()] ?? name;
  return `${pretty} ${version.replace(/^v/, "")}`;
}

function jsEngine(engine) {
  const name = engine.split(" ")[0].toLowerCase();
  return { node: "V8", deno: "V8", chromium: "V8", bun: "JavaScriptCore", webkit: "JavaScriptCore", firefox: "SpiderMonkey", "quickjs-wasm": "QuickJS" }[name] ?? "?";
}

function platformName(platform, file) {
  const [os, arch] = platform.split("-");
  const system = { darwin: "macOS", linux: "Linux", win32: "Windows" }[os] ?? os;
  const processor = { arm64: "ARM64", x64: "x86-64" }[arch] ?? arch;
  return `${system} ${processor}${file.includes("rosetta") ? " (Rosetta 2)" : ""}`;
}

// ---------------------------------------------------------------------------------------------
// Speed: feynjs in each runtime against LaTeX compiling the same diagrams.

function speedTable() {
  const dir = join(RESULTS, "speed");
  const runs = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".json") && f !== "tex.json").map((f) => JSON.parse(readFileSync(join(dir, f), "utf8"))) : [];
  const tex = existsSync(join(dir, "tex.json")) ? JSON.parse(readFileSync(join(dir, "tex.json"), "utf8")) : undefined;
  const ms = (x) => (x === undefined ? "---" : x < 10 ? x.toFixed(1) : x.toFixed(0));
  const rank = (run) => ORDER.indexOf(run.engine.split(" ")[0].toLowerCase());
  const jsRows = runs.sort((a, b) => rank(a) - rank(b)).map((run) =>
    [`feynjs, ${runtimeName({ engine: run.engine.replace(/^(\w+)/, (m) => m.toLowerCase()) })}`, "layout and SVG", ms(run.atlas.medianMs), ms(run.atlas.p95Ms), "---"].join(" & ") + " \\\\");
  const texRow = (label, what, alone, together) =>
    [label, what, alone ? ms(alone.medianSeconds * 1000) : "---", "---", together?.perDiagramSeconds !== undefined ? ms(together.perDiagramSeconds * 1000) : "---"].join(" & ") + " \\\\";
  const texRows = tex ? [
    texRow("feynjs export, pdf\\LaTeX{}", "typesetting", tex.feynjsPdflatex, tex.oneDocument.feynjsPdflatex),
    texRow("\\tikzfeynman{}, Lua\\LaTeX{}", "layout and typesetting", tex.tikzFeynmanLualatex, tex.oneDocument.tikzFeynmanLualatex),
  ] : [];
  const cpu = runs[0]?.cpu ?? "";
  return [
    `% Generated by scripts/paper-tables.mjs from ${RESULTS}/speed. Do not edit. Machine: ${cpu}.`,
    "\\begin{tabular}{l l r r r}",
    "\\toprule",
    " & & \\multicolumn{2}{c}{ms per diagram} & ms added by \\\\",
    "Tool & Work & median & 95th pct. & one more diagram \\\\",
    "\\midrule",
    ...jsRows,
    ...(texRows.length ? ["\\midrule", ...texRows] : []),
    "\\bottomrule",
    "\\end{tabular}",
    "",
  ].join("\n");
}
